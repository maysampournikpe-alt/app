// Rebuilds messages/<locale>/index.ts so every JSON file in that folder is included.
// Run: node scripts/gen-message-index.mjs
import { readdirSync, writeFileSync, statSync } from "node:fs";
import { join } from "node:path";

for (const locale of readdirSync("messages")) {
  const dir = join("messages", locale);
  if (!statSync(dir).isDirectory()) continue;
  const files = readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
  const names = files.map((f) => f.replace(/\.json$/, ""));
  const ident = (n) => "ns_" + n.replace(/[^a-zA-Z0-9]/g, "_");
  const src =
    `// AUTO-GENERATED by scripts/gen-message-index.mjs\n` +
    names.map((n) => `import ${ident(n)} from "./${n}.json";`).join("\n") +
    `\n\nconst messages = {\n` +
    names.map((n) => `  ${JSON.stringify(n)}: ${ident(n)},`).join("\n") +
    `\n};\nexport default messages;\n`;
  writeFileSync(join(dir, "index.ts"), src);
  console.log(`${locale}: ${names.length} files`);
}
