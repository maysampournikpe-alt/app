// Generates src/lib/server/db-init-sql.ts from prisma/schema.prisma.
//
// Why: on free hosting (Vercel) there is no step where we can run database
// migrations for SQLite, so the app creates its own tables on first use.
// Run `npm run db:sql` after changing prisma/schema.prisma.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const sql = execSync(
  "npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script",
  { encoding: "utf8" },
);

const statements = sql
  .split(";")
  .map((s) => s.replace(/--.*$/gm, "").trim())
  .filter(Boolean)
  // Make every statement safe to run again on an existing database.
  .map((s) =>
    s
      .replace(/^CREATE TABLE /, "CREATE TABLE IF NOT EXISTS ")
      .replace(/^CREATE UNIQUE INDEX /, "CREATE UNIQUE INDEX IF NOT EXISTS ")
      .replace(/^CREATE INDEX /, "CREATE INDEX IF NOT EXISTS "),
  );

const out = `// AUTO-GENERATED by scripts/gen-init-sql.mjs. Do not edit by hand.
// SQL that creates every table if it does not exist yet (SQLite only).
export const INIT_SQL: string[] = ${JSON.stringify(statements, null, 2)};
`;
writeFileSync("src/lib/server/db-init-sql.ts", out);
console.log(`Wrote ${statements.length} statements to src/lib/server/db-init-sql.ts`);
